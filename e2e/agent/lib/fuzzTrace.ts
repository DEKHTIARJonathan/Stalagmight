/**
 * Trace record/replay for the undo fuzzers: the artefact that turns "seed 16,
 * 40 iterations, somewhere in there" into a list of commands you can read,
 * replay, shrink and transcribe into a Rust test.
 *
 * ## Why a trace and not just a seed
 *
 * A seed already reproduces a run exactly - that was designed in from the start.
 * What a seed does NOT give you is the ability to change the run. Triage is
 * mostly "which of these 37 mutations actually matter", and with only a seed the
 * answer costs a sweep of other seeds and a human bisecting by eye. A trace is
 * the run's RESOLVED decisions - every generator draw already collapsed into a
 * concrete `projectStore` action and its arguments - so a subset of it is still
 * a runnable scenario. That is what makes automatic minimization possible
 * (`fuzzShrink.ts`), and it is why the trace stores resolved args rather than the
 * rng state: replay needs neither the generators nor the PRNG, so a shrunk trace
 * is not tied to the generator version that produced it.
 *
 * ## What is recorded, and what is deliberately not
 *
 * One entry per MOVE the scenario made, in order: mutations with their action
 * and args, single-step and multi-step history moves, save/reload boundary
 * crossings, and Repair.
 *
 * The final unwind/rewind is NOT recorded. It is a function of the state the run
 * ends in ("undo to 0, redo to the top"), so recording it would pin a depth that
 * a shrunk trace no longer has. The replayer always regenerates it instead - see
 * `fuzzShrink.ts` for why that is also what makes removal a sound shrink step.
 *
 * ## Recording is observe-only
 *
 * `TraceRecorder` draws nothing, reads no app state and is called AFTER the
 * decision it records. Recording therefore cannot move a seed's trajectory, and
 * the two faithfulness repros (bug 1 at fractal seed 1 x40 strict, bug 8 at
 * fractal seed 14 x6 tolerant) are re-verified with recording active.
 *
 * ## Schema v2
 *
 * v2 adds the step kinds the import/export fuzzers need: UI clicks and typed
 * input, a native file dialog and what it was answered with, a generated or
 * corpus-sourced input file, an export, a map click, and a project reload.
 *
 * `readTrace` requires an EXACT version match, so bumping this invalidates
 * locally-held trace files from the previous version. That is deliberate and
 * cheap: a trace is a session artifact under `.agent-artifacts/` (gitignored,
 * regenerated by re-running the seed), never a fixture and never checked in.
 * The alternative - migrating v1 files - would mean guessing what a v1 recording
 * meant under a step vocabulary that did not exist when it was written.
 *
 * The v1 step kinds are all still valid v2 steps; only the FILE version moved.
 *
 * ## Schema v3: a corpus file is named by its id, never by its name
 *
 * v3 changes what a `corpusFile` step carries, and renames the field to say so:
 * `corpusRel` (the file's corpus-RELATIVE PATH, on the argument that a trace is
 * a local artifact) became `corpusId`. It is not a local artifact: a trace is
 * the one thing the docs tell an operator to attach to a bug report and hand to
 * a shrinker, and a survey filename can name a cave system, a landowner or an
 * unreleased project - which is why every OTHER surface in this harness already
 * carries `fixtureCorpus.corpusFileId` instead. v3 carries the id there too, so
 * the whole file is publishable rather than nearly so.
 *
 * The guarantee is enforced at both ends rather than trusted to the recorder:
 * `writeTrace` refuses to emit a corpus step named any other way, and
 * `readTrace` refuses to accept one. The corpus ROOT goes the same way - it is
 * an absolute path on the recorder's disk, so it joins `NEVER_RESTORED` and
 * stops being written into the trace header.
 *
 * The FILE version moved rather than the field being read leniently. A v2 file
 * on disk still CONTAINS such a path, under a name this build no longer reads,
 * so refusing it by version says "recorded by an older build, re-run the seed"
 * instead of failing per-step on a field that is missing or merely looks wrong -
 * and it guarantees nothing migrates a leaked name forward.
 */
import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';

import { shortId } from './crc32';

/** Current trace schema. Bumped when a step shape changes incompatibly. */
export const TRACE_VERSION = 3;

/**
 * One replayable move.
 *
 * `save` is the whole boundary crossing (save to a temp path, close, reopen), not
 * just the write: the three are one atomic thing as far as the model is
 * concerned, and splitting them would let a shrink produce a trace that saved
 * without reopening.
 */
export type TraceStep =
  | { kind: 'mutate'; action: string; args: unknown[]; label: string }
  // One literal `kind` per member, not `'undo' | 'redo'` on a shared one: the
  // replayer narrows on it, and TypeScript will not discharge a member whose
  // discriminant is itself a union.
  | { kind: 'undo' }
  | { kind: 'redo' }
  | { kind: 'undoTo'; steps: number }
  | { kind: 'redoTo'; steps: number }
  | { kind: 'save' }
  | { kind: 'repair' }
  // ---- v2: the import/export vocabulary -----------------------------------
  /** A click on a `data-testid`. The label is what a human reads in a shrink. */
  | { kind: 'ui'; testid: string; double?: boolean; label: string }
  /** Text typed, an option selected, or a checkbox set on a `data-testid`. */
  | { kind: 'input'; testid: string; value: string; mode: 'type' | 'select' | 'check'; label: string }
  /**
   * A control that opens a native file dialog, and the answer given to it.
   * `rel` is null for a cancel, one path for a save or single open, a list for a
   * multi-select.
   */
  | { kind: 'fileDialog'; trigger: string; dialog: 'open' | 'save'; rel: string | string[] | null; label: string }
  /**
   * An input file built from a `surveyFileSpecs` spec and written at `rel`.
   * The SPEC travels, not the bytes: `surveyFileWriters.ts` is a pure function
   * of it, so the replayer rebuilds the identical file without the trace
   * carrying a fixture (which the repo forbids) or a megabyte of base64.
   */
  | { kind: 'genFile'; spec: unknown; rel: string; label: string }
  /**
   * An input file taken from the replayer's OWN private corpus and copied to
   * `rel`.
   *
   * `corpusId` is the entry's PUBLISHABLE ID - `fixtureCorpus.corpusFileId`, a
   * 5-hex fold of its corpus-relative path - and never the path itself. The
   * replayer resolves that id against its own `STALAGMIGHT_FUZZ_CORPUS_DIR`
   * (`corpusEntryFor` looks up either key), so the trace carries no name, no
   * root and no content, and a replayer whose corpus holds no file with that id
   * skips the step and counts it.
   *
   * The field is NAMED for what it holds. It was `corpusRel` in v2, when it held
   * the path, and a `...Rel` field quietly holding a crc id is exactly how the
   * next reader talks themselves into putting a path back in it.
   */
  | { kind: 'corpusFile'; corpusId: string; rel: string; label: string }
  /** A file handed to the app by path rather than through a dialog. */
  | { kind: 'route'; rel: string; label: string }
  | { kind: 'mapClick'; lngLat: [number, number]; label: string }
  | { kind: 'export'; format: string; options: unknown; rel: string; label: string }
  /** Reopen the named tracked fixture, discarding the current project. */
  | { kind: 'reload'; fixture: string };

/**
 * `mutate` actions whose `args[0]` is an INPUT FILE PATH, not a value.
 *
 * The undo-redo-fuzz v3 import group drives the store's file importers, and a
 * store action that takes a path is the one shape a `mutate` step cannot carry
 * verbatim: the recording machine's absolute path means nothing on a replayer,
 * and a trace is meant to be attachable to a bug report. So those steps record a
 * SESSION-RELATIVE path (paired with a `genFile` step carrying the spec to
 * rebuild the file from), and the replayer resolves it against its own files
 * directory - keyed on exactly this set, because a trace has no other way to say
 * "argument zero is a path".
 *
 * It is a security boundary as much as a portability one, and the same one every
 * v2 `rel` field has: without the check below, a hand-written trace could name
 * `/etc/shadow` (or `../../../.ssh/id_rsa`) as the file for `executeTmlImport`
 * and have the app open and parse it. `validateStep` refuses that outright, so
 * the only thing a trace can point the importers at is a path inside the session
 * directory the replayer chose.
 *
 * Kept HERE rather than beside the generators because this file is the one that
 * reads untrusted input; `undoRedoFuzz.ts` imports it for resolution and
 * `undoRedoFuzzImportActions.test.ts` pins that every file-bearing generator
 * names one of these.
 */
export const FILE_ARG_ACTIONS: ReadonlySet<string> = new Set([
  'importDmp',
  'executeTmlImport',
  'executeCompassImport',
  'executeWallsImport',
  'executeGpxImport',
  'calculateFileHash',
]);

/** A failure, reduced to the parts that identify it across a shrink. */
export interface FailureSignature {
  /** First line of the failure, with every run of digits replaced by `N`. */
  headline: string;
  /** First differing path, with array indices normalized (`shots[3]` -> `shots[*]`). */
  path: string | null;
  /** The `error:` line of a move that failed outright, digits normalized. */
  error: string | null;
  /** Every classifier id the message named, sorted and deduped. */
  classifiers: string[];
}

export interface FuzzTrace {
  v: number;
  scenario: string;
  /** The seed that produced it. Replay does not need it; triage does. */
  seed: number;
  iterations: number;
  fixture: string;
  /** Generator stream the recording ran on (`v1` / `v2`), for the header only. */
  stream: string;
  /** The `STALAGMIGHT_FUZZ_*` / `STALAGMIGHT_PERSIST_FUZZ_*` knobs that were set. */
  env: Record<string, string>;
  gitRev: string;
  recordedAt: string;
  /** Null when the run passed and the trace was written because of the env var. */
  failure: { message: string; signature: FailureSignature } | null;
  steps: TraceStep[];
}

/** Env knobs that change what a run does, and so belong in a trace header. */
const RECORDED_ENV_PREFIXES = ['STALAGMIGHT_FUZZ_', 'STALAGMIGHT_PERSIST_FUZZ_'];

/**
 * Knobs that match the prefixes above and are STILL never carried or restored.
 *
 * Each names an output or input PATH rather than what the run does, and each is
 * set by the caller that is about to run - so honouring a file's opinion about
 * them lets that file decide where this process writes (`_TRACE`), what it
 * replays next (`_REPLAY`), or which directory tree it walks and copies out of
 * (`_CORPUS_DIR`). The exclusion has to hold on BOTH sides, or it is a
 * convention rather than a boundary.
 *
 * `_CORPUS_DIR` is also the header's half of the v3 privacy rule. It is an
 * absolute path on the RECORDER's disk, and one whose own segments can name a
 * cave system or a landowner, so carrying it would put back in the header
 * exactly what the `corpusFile` step stopped putting in the steps - and
 * `scenario-run.ts` prints every restored knob as `KEY=value`. A replay resolves
 * corpus ids against the corpus the REPLAYER configured, which is the only one
 * it can read anyway.
 */
const NEVER_RESTORED = [
  'STALAGMIGHT_FUZZ_TRACE',
  'STALAGMIGHT_FUZZ_REPLAY',
  'STALAGMIGHT_FUZZ_CORPUS_DIR',
];

/**
 * Restore a trace's recorded environment - filtered to the SAME prefixes the
 * recorder writes.
 *
 * The filter has to exist on BOTH sides. `recordedEnv` applying it is a
 * producer-side convention; a trace is a file, and a file arrives from wherever
 * the reader got it - the docs tell people to attach one to a bug report and
 * shrink it. Restoring its keys verbatim would let that file set `PATH`,
 * `NODE_OPTIONS`, `LD_PRELOAD` or `RUSTFLAGS` for a run that then invokes cargo,
 * launches the app, and (in `fuzz-matrix`) spreads the whole environment into
 * every child process.
 *
 * Returns what it applied and what it refused, so the caller can print both:
 * a silently dropped knob would be a replay that quietly is not the recording.
 */
export function restoreTraceEnv(recorded: Readonly<Record<string, string>>): {
  applied: [string, string][];
  refused: string[];
} {
  const applied: [string, string][] = [];
  const refused: string[] = [];
  for (const [key, value] of Object.entries(recorded)) {
    if (NEVER_RESTORED.includes(key)) {
      refused.push(key);
      continue;
    }
    if (RECORDED_ENV_PREFIXES.some((prefix) => key.startsWith(prefix))) {
      process.env[key] = value;
      applied.push([key, value]);
    } else {
      refused.push(key);
    }
  }
  return { applied, refused };
}

function recordedEnv(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value === undefined) continue;
    // The trace's own path is not part of what the run DOES, and carrying it
    // would make a replayed trace overwrite the file it came from.
    if (NEVER_RESTORED.includes(key)) continue;
    if (RECORDED_ENV_PREFIXES.some((prefix) => key.startsWith(prefix))) out[key] = value;
  }
  return out;
}

function gitRev(): string {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

/**
 * A corpus file's publishable id: exactly what `crc32.shortId` produces, and
 * therefore exactly what `fixtureCorpus.corpusFileId` produces.
 *
 * It is also the test that tells an id apart from a corpus-relative path, which
 * is sound in one direction and that is the direction used: `discoverCorpus`
 * only ever yields paths carrying an importable extension, so a real path can
 * never be five bare hex characters.
 */
const CORPUS_ID = /^[0-9a-f]{5}$/;

/** A corpus reference reduced to its id. Idempotent, by the rule above. */
function asCorpusId(reference: string): string {
  return CORPUS_ID.test(reference) ? reference : shortId(reference);
}

/**
 * The point a corpus file's real name stops existing.
 *
 * A scenario holds BOTH halves - it drew the entry from the inventory, so it has
 * the id and the corpus-relative path it needs to materialize the file - and
 * `importDialogFuzz` hands over the id. This fold is what makes that a property
 * of the recorder rather than of one caller remembering: hand it either, and a
 * recorded step carries the id.
 *
 * Folding HERE rather than in `writeTrace` means `snapshot()`, `build()` and
 * every shrink candidate carry the id too, so there is no window in which an
 * in-memory step and a written step disagree about what a trace may say. And it
 * is a fold rather than a throw because the caller is mid-run, usually holding a
 * failure worth keeping.
 */
function redactStep(step: TraceStep): TraceStep {
  if (step.kind !== 'corpusFile') return step;
  return { ...step, corpusId: asCorpusId(step.corpusId) };
}

/**
 * Collects the resolved move list for one run (or, for a per-cycle scenario, one
 * cycle). Observe-only: it never draws, never reads app state and never decides
 * anything.
 */
export class TraceRecorder {
  private steps: TraceStep[] = [];

  record(step: TraceStep): void {
    this.steps.push(redactStep(step));
  }

  /** Drop everything recorded so far. Used by scenarios whose iterations are independent. */
  reset(): void {
    this.steps = [];
  }

  get length(): number {
    return this.steps.length;
  }

  snapshot(): TraceStep[] {
    return this.steps.map((step) => ({ ...step }));
  }

  build(meta: {
    scenario: string;
    seed: number;
    iterations: number;
    fixture: string;
    stream: string;
    failure: { message: string } | null;
  }): FuzzTrace {
    return {
      v: TRACE_VERSION,
      scenario: meta.scenario,
      seed: meta.seed,
      iterations: meta.iterations,
      fixture: meta.fixture,
      stream: meta.stream,
      env: recordedEnv(),
      gitRev: gitRev(),
      recordedAt: new Date().toISOString(),
      failure: meta.failure
        ? { message: meta.failure.message, signature: failureSignature(meta.failure.message) }
        : null,
      steps: this.snapshot(),
    };
  }
}

/**
 * Write a trace, refusing outright to emit one that names a corpus file.
 *
 * `TraceRecorder.record` already folded every corpus step to its id, so this
 * fires only for a trace assembled some other way - a shrink candidate built
 * from steps a future caller synthesised, or a hand-edited file being rewritten.
 * That is the case worth a hard failure rather than a silent fold: the write is
 * what makes the name durable and attachable, and a fold here would quietly
 * bless a code path that believed it could carry the path around.
 *
 * The refusal deliberately does not quote the offending value - an exception
 * message ends up in a log, which is the surface this whole rule protects.
 */
export function writeTrace(filePath: string, trace: FuzzTrace): string {
  trace.steps.forEach((step, index) => {
    if (step.kind === 'corpusFile' && !CORPUS_ID.test(step.corpusId)) {
      throw new Error(
        `refusing to write ${filePath}: step ${index + 1} names a corpus file by something ` +
          `other than its id, and a trace is an artifact people attach to bug reports`,
      );
    }
  });
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(trace, null, 2)}\n`, 'utf8');
  return filePath;
}

/** Every `kind` a step may carry. Anything else is not a step this build runs. */
const STEP_KINDS = new Set([
  'mutate',
  'undo',
  'redo',
  'undoTo',
  'redoTo',
  'save',
  'repair',
  'ui',
  'input',
  'fileDialog',
  'genFile',
  'corpusFile',
  'route',
  'mapClick',
  'export',
  'reload',
]);

const INPUT_MODES = new Set(['type', 'select', 'check']);

/** A field that must be a non-empty string. */
function requireText(value: unknown, field: string, where: string): string {
  if (typeof value !== 'string' || value === '') {
    throw new Error(`${where} has ${field} ${JSON.stringify(value)}; must be a non-empty string`);
  }
  return value;
}

/**
 * Every `rel` in a v2 step must stay INSIDE the session directory the replayer
 * chose. Absolute paths and `..` traversal are rejected outright.
 *
 * Same argument as `NEVER_RESTORED` above, applied to paths instead of to the
 * environment: a trace is a file, and a file arrives from wherever the reader
 * got it - the docs tell people to attach one to a bug report and shrink it.
 * These fields are joined against a session directory and then WRITTEN to
 * (`genFile`, `corpusFile`, `export`) or handed to the app to open. Honouring
 * `/etc/cron.d/x` or `../../../.ssh/authorized_keys` would let the file choose
 * what a replay creates, overwrites, or opens - the same "the file decides where
 * this process writes" hole the trace-path env knob is refused for.
 *
 * Windows spellings are checked explicitly: `path.isAbsolute` on Linux does not
 * consider `C:\x` or `\\server\share` absolute, and a trace is portable.
 */
function requireSessionRelative(value: unknown, field: string, where: string): void {
  const text = requireText(value, field, where);
  if (
    path.isAbsolute(text) ||
    text.startsWith('/') ||
    text.startsWith('\\') ||
    /^[A-Za-z]:/.test(text)
  ) {
    throw new Error(`${where} has an absolute ${field} ${JSON.stringify(text)}; must be session-relative`);
  }
  if (text.split(/[/\\]/).some((segment) => segment === '..')) {
    throw new Error(`${where} has ${field} ${JSON.stringify(text)} escaping the session directory`);
  }
}

/**
 * A corpus reference a trace is allowed to carry: the publishable id, and
 * nothing that could be a name.
 *
 * The message does not quote the value. A trace whose corpus step carries a real
 * path is precisely a leaked survey name, and `readTrace`'s exceptions are
 * printed by `scenario-run.ts` and `fuzz-shrink.ts`.
 */
function requireCorpusId(value: unknown, field: string, where: string): void {
  const text = requireText(value, field, where);
  if (!CORPUS_ID.test(text)) {
    throw new Error(
      `${where} has a ${field} that is not a corpus id (5 hex characters). A trace names a ` +
        `corpus file by its id, never by its path; re-record it on this build.`,
    );
  }
}

/**
 * Validate one step's SHAPE.
 *
 * The file is the untrusted input, and these fields reach control flow: `kind`
 * selects the branch (an unrecognised one used to fall through to the
 * history-move arm and replay as a redo), `steps` is clamped with `Math.min`
 * against the reach - which does not bound it from BELOW, so a negative moved
 * the model cursor the wrong way - `args` is spread into a store action, and
 * every v2 `rel` becomes a path the replayer writes to or opens.
 */
function validateStep(step: unknown, index: number, filePath: string): void {
  const where = `trace ${filePath} step ${index + 1}`;
  if (typeof step !== 'object' || step === null) throw new Error(`${where} is not an object`);
  const candidate = step as Partial<TraceStep> & Record<string, unknown>;
  if (typeof candidate.kind !== 'string' || !STEP_KINDS.has(candidate.kind)) {
    throw new Error(`${where} has kind ${JSON.stringify(candidate.kind)}, which this build does not run`);
  }
  if (candidate.kind === 'mutate') {
    if (typeof candidate.action !== 'string') {
      throw new Error(`${where} is a mutation with no action name`);
    }
    if (!Array.isArray(candidate.args)) throw new Error(`${where} has args that are not an array`);
    // An action that takes a PATH is the one `mutate` shape whose arguments
    // reach the filesystem instead of the model - see `FILE_ARG_ACTIONS`.
    if (FILE_ARG_ACTIONS.has(candidate.action)) {
      requireSessionRelative(candidate.args[0], 'args[0]', `${where} (${candidate.action})`);
    }
  }
  if (candidate.kind === 'undoTo' || candidate.kind === 'redoTo') {
    const steps = candidate.steps;
    if (typeof steps !== 'number' || !Number.isSafeInteger(steps) || steps < 1) {
      throw new Error(`${where} jumps ${JSON.stringify(steps)} step(s); must be a positive integer`);
    }
  }
  if (candidate.kind === 'ui') {
    requireText(candidate.testid, 'testid', where);
    requireText(candidate.label, 'label', where);
    if (candidate.double !== undefined && typeof candidate.double !== 'boolean') {
      throw new Error(`${where} has double ${JSON.stringify(candidate.double)}; must be a boolean`);
    }
  }
  if (candidate.kind === 'input') {
    requireText(candidate.testid, 'testid', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.value !== 'string') {
      throw new Error(`${where} has value ${JSON.stringify(candidate.value)}; must be a string`);
    }
    if (typeof candidate.mode !== 'string' || !INPUT_MODES.has(candidate.mode)) {
      throw new Error(`${where} has input mode ${JSON.stringify(candidate.mode)}, which this build does not run`);
    }
  }
  if (candidate.kind === 'fileDialog') {
    requireText(candidate.trigger, 'trigger', where);
    requireText(candidate.label, 'label', where);
    if (candidate.dialog !== 'open' && candidate.dialog !== 'save') {
      throw new Error(`${where} has dialog ${JSON.stringify(candidate.dialog)}; must be 'open' or 'save'`);
    }
    const rel = candidate.rel;
    if (rel !== null) {
      // A cancel is `null`; anything else is one or more paths that get joined
      // against the session directory and answered into a native dialog.
      const paths = Array.isArray(rel) ? rel : [rel];
      if (paths.length === 0) throw new Error(`${where} answers the dialog with an empty path list`);
      paths.forEach((entry, at) => requireSessionRelative(entry, `rel[${at}]`, where));
    }
  }
  if (candidate.kind === 'genFile') {
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.spec !== 'object' || candidate.spec === null) {
      throw new Error(`${where} has no generator spec to rebuild its file from`);
    }
  }
  if (candidate.kind === 'corpusFile') {
    // Not a path check but an IDENTITY check, and it does the path check's job
    // as a side effect: an id has no separators, so it can name neither an
    // absolute path nor a traversal out of the replayer's corpus root. What it
    // is really for is the v3 rule - a trace that names a corpus file is
    // refused at the door, whoever wrote it. `rel` is a genuine path, joined
    // against the replayer's session dir, and is checked as one.
    requireCorpusId(candidate.corpusId, 'corpusId', where);
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'route') {
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'mapClick') {
    const at = candidate.lngLat;
    if (!Array.isArray(at) || at.length !== 2 || !at.every((value) => typeof value === 'number' && Number.isFinite(value))) {
      throw new Error(`${where} has lngLat ${JSON.stringify(at)}; must be two finite numbers`);
    }
    requireText(candidate.label, 'label', where);
  }
  if (candidate.kind === 'export') {
    requireText(candidate.format, 'format', where);
    requireSessionRelative(candidate.rel, 'rel', where);
    requireText(candidate.label, 'label', where);
    if (typeof candidate.options !== 'object' || candidate.options === null) {
      throw new Error(`${where} has export options ${JSON.stringify(candidate.options)}; must be an object`);
    }
  }
  if (candidate.kind === 'reload') {
    const fixture = requireText(candidate.fixture, 'fixture', where);
    // A tracked fixture is named, never pathed. `materializeFixture` already
    // takes the basename, so this is belt and braces - but it is the difference
    // between a rule and a coincidence of another module's implementation.
    if (/[/\\]/.test(fixture) || fixture === '..') {
      throw new Error(`${where} names fixture ${JSON.stringify(fixture)}; must be a bare fixture name`);
    }
  }
}

export function readTrace(filePath: string): FuzzTrace {
  const parsed = JSON.parse(fs.readFileSync(filePath, 'utf8')) as FuzzTrace;
  if (parsed.v !== TRACE_VERSION) {
    throw new Error(`trace ${filePath} is schema v${parsed.v}; this build reads v${TRACE_VERSION}`);
  }
  if (!Array.isArray(parsed.steps)) throw new Error(`trace ${filePath} has no steps array`);
  parsed.steps.forEach((step, index) => validateStep(step, index, filePath));
  return parsed;
}

/** Where a run drops its trace when it fails. */
export function defaultTracePath(artifactsDir: string, scenario: string, seed: number): string {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  return path.join(artifactsDir, 'traces', `${scenario}-seed${seed}-${stamp}.json`);
}

/**
 * Everything in a failure message that must survive a shrink, and nothing that
 * must not.
 *
 * Digits are normalized out of the headline and the error line, and array
 * indices out of the path, for one reason: removing a mutation MOVES things. The
 * depth a failure happens at, the iteration number, the section index in a diff
 * path - all of them shift when an earlier action goes away, while the defect is
 * the same defect. A signature that pinned them would reject every genuine
 * reduction and the shrinker would never make progress.
 *
 * What is NOT normalized is the shape of the sentence, the field at the end of
 * the diff path, and every classifier id the message named. Those are what say
 * WHICH bug it is, so a shrink that lands on a different defect - which smaller
 * traces genuinely do - fails the comparison and is rejected, exactly as ddmin
 * requires.
 */
export function failureSignature(message: string): FailureSignature {
  const lines = message.split('\n');
  const headline = normalizeNumbers(lines[0] ?? '');

  let firstPath: string | null = null;
  let error: string | null = null;
  const classifiers = new Set<string>();
  for (const line of lines) {
    const pathMatch = /^\s+at (\S+)$/.exec(line);
    if (pathMatch && firstPath === null) firstPath = normalizeIndices(pathMatch[1] ?? '');
    const errorMatch = /^\s+error: (.+)$/.exec(line);
    if (errorMatch && error === null) error = normalizeNumbers(errorMatch[1] ?? '');
    for (const found of line.matchAll(/(?:KNOWN OPEN APP BUG|ATTRIBUTED) \[([a-z0-9-]+)\]/g)) {
      const id = found[1];
      if (id !== undefined) classifiers.add(id);
    }
    // An absolute-invariant breach has no diff path; its text is the identity.
    const invariant = /^\s+INVARIANT: (.+)$/.exec(line);
    if (invariant && firstPath === null) firstPath = `INVARIANT:${normalizeNumbers(invariant[1] ?? '')}`;
  }

  return { headline, path: firstPath, error, classifiers: [...classifiers].sort() };
}

function normalizeNumbers(text: string): string {
  return text.replace(/\d+(\.\d+)?/g, 'N');
}

function normalizeIndices(text: string): string {
  return text.replace(/\[\d+\]/g, '[*]').replace(/\.\d+(\b|$)/g, '.N');
}

/** Do two failures name the same defect? */
export function sameSignature(a: FailureSignature, b: FailureSignature): boolean {
  return (
    a.headline === b.headline &&
    a.path === b.path &&
    a.error === b.error &&
    a.classifiers.length === b.classifiers.length &&
    a.classifiers.every((id, index) => id === b.classifiers[index])
  );
}

export function describeSignature(signature: FailureSignature): string {
  return [
    `  headline:    ${signature.headline}`,
    `  path:        ${signature.path ?? '(none)'}`,
    `  error:       ${signature.error ?? '(none)'}`,
    `  classifiers: ${signature.classifiers.length > 0 ? signature.classifiers.join(', ') : '(none)'}`,
  ].join('\n');
}

/** One line per step, for a human reading a shrunk trace. */
export function describeSteps(steps: readonly TraceStep[]): string {
  return steps.map((step, index) => `${String(index + 1).padStart(3, ' ')}. ${describeStep(step)}`).join('\n');
}

/**
 * One step, as a line.
 *
 * The v2 kinds print their own `label` plus the ONE fact the label cannot carry
 * - which testid, which corpus id, which format - because a shrunk trace is read
 * top to bottom by somebody deciding what to try next. A corpus step prints the
 * publishable id, which since v3 is the only thing the step has: the rule
 * `fixtureCorpus.ts` states now holds for the trace FILE as well as for the text
 * rendered from it.
 */
function describeStep(step: TraceStep): string {
  switch (step.kind) {
    case 'mutate':
      return step.label;
    case 'undoTo':
    case 'redoTo':
      return `${step.kind}(${step.steps} step(s))`;
    case 'ui':
      return `${step.double === true ? 'dblclick' : 'click'} ${step.testid} - ${step.label}`;
    case 'input':
      return `${step.mode} ${step.testid} - ${step.label}`;
    case 'fileDialog': {
      const answer =
        step.rel === null ? 'cancel' : Array.isArray(step.rel) ? `${step.rel.length} file(s)` : step.rel;
      return `${step.dialog}-dialog via ${step.trigger} -> ${answer} - ${step.label}`;
    }
    case 'genFile':
      return `genFile ${step.rel} - ${step.label}`;
    case 'corpusFile':
      // Printed, not folded: since v3 the step already holds the id, and folding
      // it again would print a tag that matched no metric key in the run beside
      // it. `asCorpusId` is what guarantees that, on both the record and the
      // read path.
      return `corpusFile #${step.corpusId} -> ${step.rel} - ${step.label}`;
    case 'route':
      return `route ${step.rel} - ${step.label}`;
    case 'mapClick':
      return `mapClick ${step.lngLat[0]},${step.lngLat[1]} - ${step.label}`;
    case 'export':
      return `export ${step.format} -> ${step.rel} - ${step.label}`;
    case 'reload':
      return `reload ${step.fixture}`;
    default:
      return step.kind;
  }
}

